let tables: Tables | null = null;

function getTables(): Tables {
  if (tables) return tables;
  const rev = new Uint8Array(H);
  for (let i = 0; i < H; i++) {
    let r = 0;
    for (let b = 0; b < 5; b++) r |= ((i >> b) & 1) << (4 - b);
    rev[i] = r;
  }
  const twRe = new Float64Array(H / 2);
  const twIm = new Float64Array(H / 2);
  for (let k = 0; k < H / 2; k++) {
    twRe[k] = Math.cos((-2 * Math.PI * k) / H);
    twIm[k] = Math.sin((-2 * Math.PI * k) / H);
  }
  const preRe = new Float64Array(H);
  const preIm = new Float64Array(H);
  const postRe = new Float64Array(H);
  const postIm = new Float64Array(H);
  for (let n = 0; n < H; n++) {
    preRe[n] = Math.cos((-Math.PI * (4 * n + 1)) / (4 * M));
    preIm[n] = Math.sin((-Math.PI * (4 * n + 1)) / (4 * M));
    postRe[n] = Math.cos((-Math.PI * n) / M);
    postIm[n] = Math.sin((-Math.PI * n) / M);
  }
  tables = {
    coeffs: new Float32Array(coeffSource),
    rev,
    twRe,
    twIm,
    preRe,
    preIm,
    postRe,
    postIm,
    re: new Float64Array(H),
    im: new Float64Array(H),
    g: new Float64Array(N),
    a: new Float64Array(M),
    b: new Float64Array(M),
    c: new Float64Array(M),
    s: new Float64Array(M),
  };
  return tables;
}

/** The prototype filter as float32, e.g. for reference implementations. */
export function qmfCoefficients(): Float32Array {
  return getTables().coeffs;
}

/** In-place radix-2 forward FFT of size 32 (e^{−i} kernel). Input must
    already be in bit-reversed order. */
function fft32(re: Float64Array, im: Float64Array, twRe: Float64Array, twIm: Float64Array): void {
  for (let size = 2, step = H / 2; size <= H; size <<= 1, step >>= 1) {
    const half = size >> 1;
    for (let start = 0; start < H; start += size) {
      for (let k = 0, t = 0; k < half; k++, t += step) {
        const a = start + k;
        const b = a + half;
        const wr = twRe[t];
        const wi = twIm[t];
        const br = re[b];
        const bi = im[b];
        const tr = br * wr - bi * wi;
        const ti = br * wi + bi * wr;
        const ar = re[a];
        const ai = im[a];
        re[b] = ar - tr;
        im[b] = ai - ti;
        re[a] = ar + tr;
        im[a] = ai + ti;
      }
    }
  }
}

/** out[k] = Σn x[n]·cos(π/64·(n+½)(k+½)) (DCT-IV, 64 points), or with
    `sine` the DST-IV Σn x[n]·sin(…), computed as DCT-IV of the reversed
    input with odd outputs negated. */
function dct4(x: Float64Array, out: Float64Array, sine: boolean, T: Tables): void {
  const re = T.re;
  const im = T.im;
  const rev = T.rev;
  const preRe = T.preRe;
  const preIm = T.preIm;
  for (let n = 0; n < H; n++) {
    const u = sine ? x[M - 1 - 2 * n] : x[2 * n];
    const w = sine ? x[2 * n] : x[M - 1 - 2 * n];
    const r = rev[n];
    re[r] = u * preRe[n] - w * preIm[n];
    im[r] = u * preIm[n] + w * preRe[n];
  }
  fft32(re, im, T.twRe, T.twIm);
  const postRe = T.postRe;
  const postIm = T.postIm;
  if (sine) {
    for (let k = 0; k < H; k++) {
      out[2 * k] = re[k] * postRe[k] - im[k] * postIm[k];
      out[M - 1 - 2 * k] = re[k] * postIm[k] + im[k] * postRe[k];
    }
  } else {
    for (let k = 0; k < H; k++) {
      out[2 * k] = re[k] * postRe[k] - im[k] * postIm[k];
      out[M - 1 - 2 * k] = -(re[k] * postIm[k] + im[k] * postRe[k]);
    }
  }
}

/** Analysis side for one channel (ProcessForward), fed a frame at a time. */
export class QmfAnalysis {
  /** Time-ordered input: `analysisHistory` samples of the previous frames,
      then the current frame. */
  private readonly hist: Float32Array;
  private frameLength = 0;

  constructor(maxFrameLength: number) {
    this.hist = new Float32Array(analysisHistory + maxFrameLength);
  }

  /** Append the next frame of input (`length` samples from `input`). */
  loadFrame(input: Float32Array | null, length: number): void {
    const hist = this.hist;
    // Keep the newest `analysisHistory` samples of what was there.
    hist.copyWithin(0, this.frameLength, this.frameLength + analysisHistory);
    if (input) hist.set(input.subarray(0, length), analysisHistory);
    else hist.fill(0, analysisHistory, analysisHistory + length);
    this.frameLength = length;
  }

  /** Forward-transform timeslot `ts` of the loaded frame into 64 complex
      subband samples. */
  forward(ts: number, outRe: Float64Array, outIm: Float64Array): void {
    const T = getTables();
    const c = T.coeffs;
    const hist = this.hist;
    const g = T.g;
    const n0 = analysisHistory + ts * subbands + subbands - 1; // newest sample of this timeslot
    for (let j = 0; j < N; j++) {
      const p = n0 - j;
      g[j] = hist[p] * c[j] + hist[p - 128] * c[j + 128] + hist[p - 256] * c[j + 256] +
        hist[p - 384] * c[j + 384] + hist[p - 512] * c[j + 512];
    }
    // Fold the 128 windowed values onto 64 (see the header comment).
    const a = T.a;
    const b = T.b;
    for (let m = 0; m < M; m++) {
      const lo = m < 127 ? g[m + 1] : -g[0];
      const hiIndex = 127 - m;
      const hi = hiIndex < 127 ? g[hiIndex + 1] : -g[0];
      a[m] = lo - hi;
      b[m] = lo + hi;
    }
    dct4(a, outRe, false, T);
    dct4(b, outIm, true, T);
  }

  reset(): void {
    this.hist.fill(0);
    this.frameLength = 0;
  }
}

/** Synthesis side for one object (ProcessInverse). */
export class QmfSynthesis {
  /** The last ten v vectors (Cavern's 1280-sample inputStreamInverse). */
  private readonly ring = new Float64Array(10 * N);
  private slot = 0;
  /** Consecutive silent timeslots; after ten the output is exactly zero. */
  private silentRun = 10;

  /** Inverse-transform one timeslot of 64 complex subband samples into 64
      output samples at `out[offset..]`, scaled by `gain`. */
  inverse(inRe: Float64Array, inIm: Float64Array, out: Float32Array, offset: number, gain: number): void {
    const T = getTables();
    const C = T.c;
    const S = T.s;
    dct4(inRe, C, false, T);
    dct4(inIm, S, true, T);
    this.slot = this.slot === 0 ? 9 : this.slot - 1;
    const v = this.ring;
    const base = this.slot * N;
    const scale = 1 / subbands;
    for (let m = 0; m < M; m++) {
      const c = C[m];
      const sn = S[m];
      v[base + m] = (sn - c) * scale;
      v[base + N - 1 - m] = (c + sn) * scale;
    }
    this.silentRun = 0;
    this.window(out, offset, gain);
  }

  /** A timeslot whose subband input is all zero: skips the FFT, and once the
      filter memory has drained, the windowing too. */
  inverseSilent(out: Float32Array, offset: number): void {
    this.slot = this.slot === 0 ? 9 : this.slot - 1;
    if (this.silentRun >= 10) {
      out.fill(0, offset, offset + subbands);
      return;
    }
    this.ring.fill(0, this.slot * N, this.slot * N + N);
    this.silentRun++;
    this.window(out, offset, 1);
  }

  /** output[i] = Σj' v(t−2j')[i]·c[128j'+i] + v(t−2j'−1)[64+i]·c[128j'+64+i]. */
  private window(out: Float32Array, offset: number, gain: number): void {
    const c = getTables().coeffs;
    const v = this.ring;
    const s = this.slot;
    // Slot of v(t−m) is (s + m) % 10.
    const b0 = s * N;
    const b1 = ((s + 1) % 10) * N + 64;
    const b2 = ((s + 2) % 10) * N;
    const b3 = ((s + 3) % 10) * N + 64;
    const b4 = ((s + 4) % 10) * N;
    const b5 = ((s + 5) % 10) * N + 64;
    const b6 = ((s + 6) % 10) * N;
    const b7 = ((s + 7) % 10) * N + 64;
    const b8 = ((s + 8) % 10) * N;
    const b9 = ((s + 9) % 10) * N + 64;
    for (let i = 0; i < subbands; i++) {
      const sum =
        v[b0 + i] * c[i] + v[b1 + i] * c[64 + i] +
        v[b2 + i] * c[128 + i] + v[b3 + i] * c[192 + i] +
        v[b4 + i] * c[256 + i] + v[b5 + i] * c[320 + i] +
        v[b6 + i] * c[384 + i] + v[b7 + i] * c[448 + i] +
        v[b8 + i] * c[512 + i] + v[b9 + i] * c[576 + i];
      out[offset + i] = sum * gain;
    }
  }

  reset(): void {
    this.ring.fill(0);
    this.slot = 0;
    this.silentRun = 10;
  }
}
